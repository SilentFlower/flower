const { contextBridge, ipcRenderer, webUtils } = require("electron");
const invoke = (name, ...args) => ipcRenderer.invoke(`flower:${name}`, ...args);

contextBridge.exposeInMainWorld("flower", {
	state: () => invoke("state"),
	setTitlebarTheme: (mode) => invoke("titlebar-theme", mode),
	setPanelExpansion: (width) => invoke("panel-expansion", width),
	saveModel: (input) => invoke("save-model", input),
	listModels: (service, revision) => invoke("list-models", service, revision),
	modelEffortPreset: (service, model) => invoke("model-effort-preset", service, model),
	chooseModel: (id, revision) => invoke("choose-model", id, revision),
	chooseModelService: (id, revision) => invoke("choose-model-service", id, revision),
	setModelEffort: (effort, revision) => invoke("set-model-effort", effort, revision),
	setWriteMode: (session, mode) => invoke("set-write-mode", session, mode),
	saveInstructions: (text) => invoke("save-instructions", text),
	decideWrite: (id, allowed) => invoke("decide-write", id, allowed),
	answerQuestion: (id, selection) => invoke("answer-question", id, selection),
	chooseWorkspace: () => invoke("choose-workspace"),
	newSession: (session) => invoke("new-session", session),
	selectSession: (session) => invoke("select-session", session),
	gitChanges: (id) => invoke("git-changes", id),
	gitDifference: (id, path, group) => invoke("git-difference", id, path, group),
	gitStage: (id, path, action) => invoke("git-stage", id, path, action),
	gitCommit: (id, message) => invoke("git-commit", id, message),
	terminalOpen: (session, cols, rows) => invoke("terminal-open", session, cols, rows),
	terminalInput: (session, id, data) => invoke("terminal-input", session, id, data),
	terminalResize: (session, id, cols, rows) => invoke("terminal-resize", session, id, cols, rows),
	terminalClose: (session, id) => invoke("terminal-close", session, id),
	browserNavigate: (session, url) => invoke("browser-navigate", session, url),
	browserAction: (session, action) => invoke("browser-action", session, action),
	browserBounds: (session, bounds) => invoke("browser-bounds", session, bounds),
	backgroundTasks: () => invoke("background-tasks"),
	cancelBackgroundTask: (session, id) => invoke("cancel-background-task", session, id),
	automationState: () => invoke("automation-state"),
	automationSkills: (workspace) => invoke("automation-skills", workspace),
	saveAutomation: (id, input) => invoke("save-automation", id, input),
	enableAutomation: (id, enabled) => invoke("enable-automation", id, enabled),
	removeAutomation: (id) => invoke("remove-automation", id),
	runAutomation: (id) => invoke("run-automation", id),
	cancelAutomation: (id) => invoke("cancel-automation", id),
	listLocalExtensions: (id) => invoke("list-local-extensions", id),
	installLocalExtension: (id, kind) => invoke("install-local-extension", id, kind),
	enableLocalExtension: (id, extension, enabled) => invoke("enable-local-extension", id, extension, enabled),
	uninstallLocalExtension: (id, extension) => invoke("uninstall-local-extension", id, extension),
	runLocalExtension: (id, extension, path) => invoke("run-local-extension", id, extension, path),
	manageSidebar: (type, id, operation, value) => invoke("manage-sidebar", type, id, operation, value),
	renameSessionWithAI: (id) => invoke("rename-session-ai", id),
	listWorkspaceEntries: (session, directory, offset) => invoke("list-workspace-entries", session, directory, offset),
	previewWorkspaceFile: (session, path) => invoke("preview-workspace-file", session, path),
	showPathMenu: (session, path, preview) => invoke("show-path-menu", session, path, preview),
	showReplyMenu: () => invoke("show-reply-menu"),
	resolveReplyPaths: (session, paths) => invoke("resolve-reply-paths", session, paths),
	workspaceFiles: (session, query) => invoke("workspace-files", session, query),
	chooseFile: (session) => invoke("choose-file", session),
	referenceFile: (session, path) => invoke("reference-file", session, path),
	dropFiles: (session, files) =>
		invoke(
			"drop-files",
			session,
			files.map((file) => webUtils.getPathForFile(file)),
		),
	pasteClipboardImage: (session) => invoke("paste-clipboard-image", session),
	pasteImage: (session, bytes) => invoke("paste-image", session, bytes),
	pasteText: (session, text) => invoke("paste-text", session, text),
	previewAttachment: (session, request, key) => invoke("attachment-preview", session, request, key),
	attachmentImage: (session, request, key) => invoke("attachment-image", session, request, key),
	removeAttachment: (session, key) => invoke("remove-attachment", session, key),
	history: (session) => invoke("history", session),
	contextUsage: (session) => invoke("context-usage", session),
	searchSessions: (query) => invoke("search-sessions", query),
	resumeInterrupted: (ids) => invoke("resume-interrupted", ids),
	dismissInterrupted: () => invoke("dismiss-interrupted"),
	compactContext: (session) => invoke("compact-context", session),
	cancelCompaction: (session) => invoke("cancel-compact", session),
	copyReply: (session, request) => invoke("copy-reply", session, request),
	turnChanges: (session, request) => invoke("turn-changes", session, request),
	undoTurnChanges: (session, request) => invoke("undo-turn-changes", session, request),
	sessionRevisionPreview: (session, request, mode) => invoke("session-revision-preview", session, request, mode),
	applySessionRevision: (session, request, mode, revision, input, undoPaths) =>
		invoke("apply-session-revision", session, request, mode, revision, input, undoPaths),
	copySessionMarkdown: (session) => invoke("copy-session-markdown", session),
	exportSessionHtml: (session) => invoke("export-session-html", session),
	sessionImageContent: (session, requests) => invoke("session-image-content", session, requests),
	copySessionImage: (session, png) => invoke("copy-session-image", session, png),
	desktopUpdateState: () => invoke("desktop-update-state"),
	checkDesktopUpdate: () => invoke("check-desktop-update"),
	restartDesktopUpdate: () => invoke("restart-desktop-update"),
	scheduleDesktopUpdate: (enabled) => invoke("schedule-desktop-update", enabled),
	openReplyLink: (url) => invoke("open-reply-link", url),
	submit: (session, input, first, skill) => invoke("submit", session, input, first, skill),
	retryRequest: (session, request) => invoke("retry-request", session, request),
	editQueueItem: (session, item, input, keep) => invoke("edit-queue-item", session, item, input, keep),
	removeQueueItem: (session, item) => invoke("remove-queue-item", session, item),
	holdQueueItem: (session, item) => invoke("hold-queue-item", session, item),
	reorderQueue: (session, ids) => invoke("reorder-queue", session, ids),
	resumeQueue: (session) => invoke("resume-queue", session),
	steerQueueItem: (session, item) => invoke("steer-queue-item", session, item),
	openSideChat: (session) => invoke("open-side-chat", session),
	sideChatHistory: (session) => invoke("side-chat-history", session),
	submitSideChat: (session, input) => invoke("submit-side-chat", session, input),
	queueToSideChat: (session, item) => invoke("queue-to-side-chat", session, item),
	cancelSideChat: (session, request, run) => invoke("cancel-side-chat", session, request, run),
	closeSideChat: (session) => invoke("close-side-chat", session),
	restoreRequestDraft: (session, request) => invoke("restore-request-draft", session, request),
	copyText: (text) => invoke("copy-text", text),
	cancel: (session, request, run) => invoke("cancel", session, request, run),
	openArtifact: (session, request, path) => invoke("open-artifact", session, request, path),
	artifactInfo: (session, path) => invoke("artifact-info", session, path),
	subscribe(callback) {
		const listener = (_event, event) => callback(event);
		ipcRenderer.on("flower:update", listener);
		return () => ipcRenderer.removeListener("flower:update", listener);
	},
});
